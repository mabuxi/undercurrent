    for (const k of keys) {
      const kw = k.split(' ');
      if (kw.length && words.slice(i, i + kw.length).join(' ') === k) { hit = [k, kw.length]; break; }
    }
    if (hit) { out.push(map.get ? map.get(hit[0]) : map[hit[0]]); hits++; i += hit[1]; } else { out.push(words[i]); i++; }
